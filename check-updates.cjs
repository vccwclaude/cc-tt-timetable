const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('app.html', 'utf8');
const source = html.slice(html.indexOf('function stampEventUpdates('), html.indexOf('function parseTextToEvents('));
const stamp = vm.runInNewContext(source + '; stampEventUpdates');
const original = { label: 'Class', time: '', color: '#fff', updatedAt: 10 };
const before = { '2026-10-14': [original] };
assert.equal(stamp(before, before, 20)['2026-10-14'][0].updatedAt, 10);
assert.equal(stamp(before, { '2026-10-14': [{ ...original, label: 'New name' }] }, 20)['2026-10-14'][0].updatedAt, 20);
assert.equal(stamp(before, { '2026-10-14': [original, original] }, 20)['2026-10-14'][1].updatedAt, 20);
assert.equal(stamp(before, { '2026-10-15': [original] }, 20)['2026-10-15'][0].updatedAt, 20);
assert.equal(Object.keys(stamp(before, {}, 20)).length, 0);
assert.equal(original.updatedAt, 10);
console.log('Update timestamps: unchanged, edited, copied, moved and deleted events passed.');
const summarize = vm.runInNewContext(html.slice(html.indexOf('function summarizeUpdates('), html.indexOf('function LatestUpdates(')) + '; summarizeUpdates');
const data = Object.fromEntries([16,17,18,19,20].map(day => ['2026-11-' + day, [{label:'eng test', updatedAt:10}]]));
assert.equal(summarize(data).length, 1);
assert.match(summarize(data)[0].dateSummary, /16.*20 Nov 2026/);
delete data['2026-11-18'];
assert.match(summarize(data)[0].dateSummary, /16.*17 Nov 2026; 19.*20 Nov 2026/);
data['2026-11-20'].push({label:'eng test', time:'10am', updatedAt:30});
assert.equal(summarize(data).length, 2);
assert.equal(summarize(data)[0].time, '10am');
assert.equal(summarize({'2026-11-01': [{label:'old'}]}).length, 0);
assert.match(summarize({'2026-12-31':[{label:'trip',updatedAt:1}], '2027-01-01':[{label:'trip',updatedAt:2}]} )[0].dateSummary, /2026.*2027/);
console.log('Update summaries: date ranges, gaps, different times and year boundaries passed.');
const buildWeeks = vm.runInNewContext('const getKey = d => d.toISOString().slice(0,10);' + html.slice(html.indexOf('function buildCalendarWeeks('), html.indexOf('function summarizeUpdates(')) + '; buildCalendarWeeks');
const dates = Array.from({length:30}, (_, i) => new Date(Date.UTC(2026,10,i+1)));
const spanData = Object.fromEntries(Array.from({length:12}, (_, i) => ['2026-11-' + (16+i), [{label:'eng test',color:'blue'}]]));
for(let day=16;day<=20;day++) spanData['2026-11-'+day].push({label:'Phuket',color:'orange'});
const weeks = buildWeeks(dates, spanData);
assert.equal(weeks[2].segments.length, 2);
assert.equal(weeks[2].lanes, 2);
assert.equal(weeks[2].segments[0].start, 1);
assert.equal(weeks[2].segments[0].end, 6);
assert.equal(weeks[3].segments[0].start, 0);
assert.equal(weeks[3].segments[0].end, 5);
assert.equal(weeks[2].segments[0].members.length, 12);
assert.equal(weeks[2].hidden.size, 11);
const gaps = buildWeeks(dates, {'2026-11-16':[{label:'x'}], '2026-11-18':[{label:'x'}]});
assert.equal(gaps.flatMap(w=>w.segments).length, 0);
const crossMonth = buildWeeks(dates, {'2026-10-31':[{label:'trip'}], '2026-11-01':[{label:'trip'}]});
assert.equal(crossMonth[0].segments[0].visible.length, 1);
assert.equal(crossMonth[0].segments[0].members.length, 2);
console.log('Multi-day bars: overlap lanes, week splits, gaps and month boundaries passed.');
